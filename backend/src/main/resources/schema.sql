-- ==============================================================================
-- Sentinel EHR Database Schema Script (DDL)
-- Compatible with Database SQL Editors (H2 PostgreSQL Mode, PostgreSQL, MySQL)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS departments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(60) UNIQUE NOT NULL,
    code VARCHAR(20) UNIQUE NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_code VARCHAR(50) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    license_number VARCHAR(100) NOT NULL,
    email VARCHAR(150),
    phone VARCHAR(50),
    address VARCHAR(500),
    status VARCHAR(30) NOT NULL DEFAULT 'VERIFIED',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(30) UNIQUE NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(60) UNIQUE NOT NULL,
    category VARCHAR(30) NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS role_permissions (
    role_id BIGINT NOT NULL,
    permission_id BIGINT NOT NULL,
    PRIMARY KEY (role_id, permission_id),
    FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE,
    FOREIGN KEY (permission_id) REFERENCES permissions(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    email VARCHAR(255) UNIQUE NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    specialization VARCHAR(255),
    department VARCHAR(255),
    department_id BIGINT,
    organization_id BIGINT,
    license_number VARCHAR(255),
    qualifications VARCHAR(255),
    years_of_experience INT,
    medical_board_state VARCHAR(255),
    verification_status VARCHAR(255) DEFAULT 'VERIFIED',
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (department_id) REFERENCES departments(id) ON DELETE SET NULL,
    FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id),
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS patients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_code VARCHAR(255) UNIQUE NOT NULL,
    abha_id VARCHAR(255),
    national_id VARCHAR(255),
    full_name VARCHAR(255) NOT NULL,
    date_of_birth DATE,
    gender VARCHAR(255),
    blood_type VARCHAR(255),
    phone VARCHAR(255),
    email VARCHAR(255),
    address VARCHAR(255),
    pin_code VARCHAR(255),
    emergency_contact VARCHAR(255),
    insurance_provider VARCHAR(255),
    insurance_policy_number VARCHAR(255),
    insurance_group_number VARCHAR(255),
    coverage_plan VARCHAR(255),
    department VARCHAR(255),
    organization_id BIGINT,
    medical_alerts VARCHAR(1000),
    dietary_habits VARCHAR(255),
    smoking_status VARCHAR(255),
    alcohol_consumption VARCHAR(255),
    exercise_routine VARCHAR(255),
    food_allergies VARCHAR(255),
    past_medical_history VARCHAR(2000),
    serious_conditions VARCHAR(2000),
    surgeries_and_procedures VARCHAR(2000),
    family_medical_history VARCHAR(2000),
    user_id BIGINT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE SET NULL,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS beds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bed_code VARCHAR(255) UNIQUE NOT NULL,
    facility_name VARCHAR(255) DEFAULT 'Sentinel General Hospital',
    department_name VARCHAR(255) NOT NULL,
    ward_name VARCHAR(255) NOT NULL,
    room_number VARCHAR(255) NOT NULL,
    bed_number VARCHAR(255) NOT NULL,
    status VARCHAR(255) DEFAULT 'AVAILABLE',
    features VARCHAR(255),
    current_encounter_id BIGINT,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS encounters (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    attending_provider_id BIGINT NOT NULL,
    encounter_type VARCHAR(255) NOT NULL,
    chief_complaint VARCHAR(1000),
    clinical_notes VARCHAR(3000),
    discharge_summary VARCHAR(3000),
    status VARCHAR(255) DEFAULT 'ADMITTED',
    admission_type VARCHAR(255),
    admission_source VARCHAR(255),
    department_name VARCHAR(255),
    admission_diagnosis_icd VARCHAR(255),
    acuity_score INT,
    assigned_bed_id BIGINT,
    encounter_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    admission_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    discharge_time TIMESTAMP,
    FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
    FOREIGN KEY (attending_provider_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (assigned_bed_id) REFERENCES beds(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS location_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_id BIGINT NOT NULL,
    bed_id BIGINT NOT NULL,
    department_name VARCHAR(255) NOT NULL,
    ward_name VARCHAR(255) NOT NULL,
    room_number VARCHAR(255) NOT NULL,
    bed_number VARCHAR(255) NOT NULL,
    start_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    end_time TIMESTAMP,
    transfer_reason VARCHAR(1000),
    transferred_by_id BIGINT,
    FOREIGN KEY (encounter_id) REFERENCES encounters(id) ON DELETE CASCADE,
    FOREIGN KEY (bed_id) REFERENCES beds(id) ON DELETE CASCADE,
    FOREIGN KEY (transferred_by_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS patient_assignments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    encounter_id BIGINT,
    staff_user_id BIGINT NOT NULL,
    assignment_type VARCHAR(40) NOT NULL,
    department_name VARCHAR(255),
    status VARCHAR(20) DEFAULT 'ACTIVE',
    start_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    end_date TIMESTAMP,
    FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
    FOREIGN KEY (encounter_id) REFERENCES encounters(id) ON DELETE CASCADE,
    FOREIGN KEY (staff_user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS break_glass_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    category VARCHAR(50) NOT NULL,
    justification VARCHAR(2000) NOT NULL,
    requested_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP NOT NULL,
    status VARCHAR(20) DEFAULT 'ACTIVE',
    client_ip VARCHAR(255),
    FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS lab_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    encounter_id BIGINT,
    ordering_provider_id BIGINT NOT NULL,
    test_name VARCHAR(255) NOT NULL,
    loinc_code VARCHAR(255),
    category VARCHAR(255) DEFAULT 'LABORATORY',
    status VARCHAR(255) DEFAULT 'ORDERED',
    specimen_barcode VARCHAR(255),
    ordered_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    specimen_collected_at TIMESTAMP,
    in_process_at TIMESTAMP,
    resulted_at TIMESTAMP,
    reviewed_at TIMESTAMP,
    reviewed_by_id BIGINT,
    clinical_notes VARCHAR(1000),
    FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
    FOREIGN KEY (encounter_id) REFERENCES encounters(id) ON DELETE CASCADE,
    FOREIGN KEY (ordering_provider_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (reviewed_by_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS lab_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lab_order_id BIGINT NOT NULL,
    parameter_name VARCHAR(255) NOT NULL,
    loinc_code VARCHAR(255),
    result_value VARCHAR(255) NOT NULL,
    unit VARCHAR(255),
    reference_range VARCHAR(255),
    is_critical BOOLEAN DEFAULT FALSE,
    flag VARCHAR(255),
    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (lab_order_id) REFERENCES lab_orders(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS imaging_orders (
