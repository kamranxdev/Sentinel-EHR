);

CREATE TABLE IF NOT EXISTS appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL,
    doctor_id BIGINT NOT NULL,
    appointment_date TIMESTAMP NOT NULL,
    status VARCHAR(255) DEFAULT 'SCHEDULED',
    stage VARCHAR(255) DEFAULT 'SCHEDULED',
    reason VARCHAR(255),
    notes VARCHAR(1000),
    insurance_verified BOOLEAN DEFAULT FALSE,
    insurance_details VARCHAR(1000),
    reports_uploaded VARCHAR(2000),
    follow_up_date TIMESTAMP,
    arrived_at TIMESTAMP,
    vitals_id BIGINT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (patient_id) REFERENCES patients(id) ON DELETE CASCADE,
    FOREIGN KEY (doctor_id) REFERENCES users(id) ON DELETE CASCADE,
    FOREIGN KEY (vitals_id) REFERENCES vitals(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS appointment_cancellations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT UNIQUE NOT NULL,
    cancelled_by_user_id BIGINT NOT NULL,
    cancelled_by_role VARCHAR(255) NOT NULL,
    cancellation_reason VARCHAR(255) NOT NULL,
    additional_comment VARCHAR(500),
    cancelled_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    refund_status VARCHAR(255) DEFAULT 'NOT_APPLICABLE',
    FOREIGN KEY (appointment_id) REFERENCES appointments(id) ON DELETE CASCADE,
    FOREIGN KEY (cancelled_by_user_id) REFERENCES users(id) ON DELETE CASCADE
);

