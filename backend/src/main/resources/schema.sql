CREATE TABLE IF NOT EXISTS appointment_lab_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    appointment_id BIGINT NOT NULL,
    test_name VARCHAR(255) NOT NULL,
    priority VARCHAR(255) DEFAULT 'ROUTINE',
